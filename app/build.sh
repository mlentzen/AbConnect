#!/usr/bin/env bash
# Builds AbConnect for the fenix 7X Pro.
#
# Requirements:
#   CIQ_HOME  Connect IQ SDK (directory containing bin/monkeyc)
#   CIQ_KEY   developer key in PKCS8 DER format
#
# Optional. Taken from .env when set and baked into the build. Left unset, the
# URL and the token are placeholders and can be entered in the app settings.
#   PROXY_URL    base URL of abconnect-proxy
#                default: https://abconnect.example.com
#   PROXY_TOKEN  this watch's token from the proxy's users.toml
#                default: replace-me
#   LOG_LEVEL    0 errors (default), 1 warnings, 2 course of events, 3 everything
#   EXPORT       1 packages a store .iq (monkeyc -e -r) for every product in
#                the manifest. Needs the real device profiles. The .iq is
#                public, so this refuses a build whose proxy URL or token is
#                anything but the placeholder.
#
# Create a key if there is none yet:
#   openssl genrsa -out dev.pem 4096
#   openssl pkcs8 -topk8 -inform PEM -outform DER -in dev.pem -out developer_key -nocrypt
set -euo pipefail

cd "$(dirname "$0")"

# load .env (optional, not checked in)
if [[ -f .env ]]; then
    set -a          # everything assigned from here on is exported
    source ./.env
    set +a
fi

CIQ_HOME="${CIQ_HOME:-/opt/ciq}"
CIQ_KEY="${CIQ_KEY:-$HOME/.ciq/developer_key}"
DEVICE="${DEVICE:-fenix7xpro}"
# 1: store package for every product in the manifest. 0: one device, .prg.
EXPORT="${EXPORT:-0}"
case "$EXPORT" in
    0|1) ;;
    *)
        echo "EXPORT must be 0 or 1." >&2
        exit 1
        ;;
esac
if [[ "$EXPORT" == 1 ]]; then
    OUTPUT="${OUTPUT:-export/abconnect.iq}"
else
    OUTPUT="${OUTPUT:-build/abconnect.prg}"
fi
# Default: monkey.jungle (per-device launcher overlays for export).
# CI syntax check: JUNGLES=monkey-ci.jungle (fenix7xpro stub only).
JUNGLES="${JUNGLES:-monkey.jungle}"
# 2 = informative: reports what matters without getting stuck on the generic
# type parameters of Storage and Method.
TYPECHECK="${TYPECHECK:-2}"

mkdir -p "$(dirname "$OUTPUT")"

# 0 = errors only. Every log line costs on the watch, and the loud paths are the
# ones that run per segment and per tick, so silence is the default and the
# trace is something you ask for.
LOG_LEVEL="${LOG_LEVEL:-0}"

# The day this build was made. Shown under the app version on the Info screen.
BUILT="$(date -u +%Y-%m-%d)"

# Write the proxy defaults into a generated source file.
#
# Connect IQ has no compiler defines and the values from .env do not reach the
# compiler on their own. The app uses them until the watch settings say
# otherwise. The file is regenerated on every build and not checked in,
# because a build that was given a real token still contains it.
GENERATED="source/BuildDefaults.mc"

# Placeholders, so a build without .env still has something to edit in the
# app. A value from the environment or from .env replaces them.
PROXY_URL="${PROXY_URL:-https://abconnect.example.com}"
PROXY_TOKEN="${PROXY_TOKEN:-replace-me}"

# The store package is downloaded by whoever installs the app. A token or a
# home-server URL baked in here would ship with it. The watch settings are
# the place for the real values.
if [[ "$EXPORT" == 1 ]]; then
    if [[ "$PROXY_TOKEN" != "replace-me" || "$PROXY_URL" != "https://abconnect.example.com" ]]; then
        echo "Refusing to export: PROXY_URL and PROXY_TOKEN are compiled into the .iq, and that file is public." >&2
        echo "Use the placeholders (https://abconnect.example.com and replace-me) and enter the real values on the watch." >&2
        exit 1
    fi
fi

# In Monkey C string literals, backslash and quotes may only appear escaped;
# line breaks not at all.
escape_literal() {
    printf '%s' "${1//$'\n'/}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

cat > "$GENERATED" <<EOF
// Generated by build.sh. Do not edit, do not check in.
import Toybox.Lang;

//! What the build knows and the source cannot: the proxy settings, when this
//! build was made, and how much it is allowed to say.
//!
//! The proxy values are placeholders unless the build was given real ones.
//! Settings stored on the watch override both.
module BuildDefaults {
    const PROXY_URL = "$(escape_literal "$PROXY_URL")";
    const PROXY_TOKEN = "$(escape_literal "$PROXY_TOKEN")";
    const BUILT = "$(escape_literal "$BUILT")";
    //! Log.ERROR .. Log.DEBUG. Read as a constant so the compiler can fold the
    //! comparisons away entirely.
    const LOG_LEVEL = $LOG_LEVEL;
}
EOF

if [[ "$EXPORT" == 1 ]]; then
    openssl pkey -inform DER -in "$CIQ_KEY" -noout
    set +o pipefail
    bits=$(openssl pkey -inform DER -in "$CIQ_KEY" -pubout -outform DER \
        | openssl pkey -pubin -inform DER -noout -text \
        | awk -F'[()]' '/Public-Key/ {gsub(/ /,"",$2); print $2; exit}')
    set -o pipefail
    if [[ "$bits" != "4096bit" ]]; then
        echo "A store package has to be signed with a 4096-bit RSA key in PKCS#8 DER form." >&2
        exit 1
    fi
    # -e packages every product in the manifest, so there is no -d.
    # -r strips debug info.
    "$CIQ_HOME/bin/monkeyc" \
        -e -r \
        -f "$JUNGLES" \
        -o "$OUTPUT" \
        -y "$CIQ_KEY" \
        -l "$TYPECHECK" \
        "$@"
else
    "$CIQ_HOME/bin/monkeyc" \
        -f "$JUNGLES" \
        -d "$DEVICE" \
        -o "$OUTPUT" \
        -y "$CIQ_KEY" \
        -l "$TYPECHECK" \
        "$@"
fi
echo "Built: $OUTPUT"
