#!/usr/bin/env bash
# Builds AbConnect for the fenix 7X Pro.
#
# Requirements:
#   CIQ_HOME  Connect IQ SDK (directory containing bin/monkeyc)
#   CIQ_KEY   developer key in PKCS8 DER format
#
# Taken from .env (optional, all of them baked into the build):
#   PROXY_URL    base URL of abconnect-proxy
#   PROXY_TOKEN  this watch's token from the proxy's users.toml
#   LOG_LEVEL    0 errors (default), 1 warnings, 2 course of events, 3 everything
#
# Create a key if there is none yet:
#   openssl genrsa -out dev.pem 4096
#   openssl pkcs8 -topk8 -inform PEM -outform DER -in dev.pem -out developer_key -nocrypt
set -euo pipefail

cd "$(dirname "$0")"

# load .env (optional, not checked in)
if [[ -f .env ]]; then
    set -a          # everything assigned from here on is exported
    source ./.env
    set +a
fi

CIQ_HOME="${CIQ_HOME:-/opt/ciq}"
CIQ_KEY="${CIQ_KEY:-$HOME/.ciq/developer_key}"
DEVICE="${DEVICE:-fenix7xpro}"
OUTPUT="${OUTPUT:-build/abconnect.prg}"
# 2 = informative: reports what matters without getting stuck on the generic
# type parameters of Storage and Method.
TYPECHECK="${TYPECHECK:-2}"

mkdir -p "$(dirname "$OUTPUT")"

# 0 = errors only. Every log line costs on the watch, and the loud paths are the
# ones that run per segment and per tick — so silence is the default and the
# trace is something you ask for.
LOG_LEVEL="${LOG_LEVEL:-0}"

# Which commit this build came from.
#
# The version in source/Version.mc is bumped by hand and says nothing about the
# builds in between. Both are shown on the Info screen; together they identify a
# build exactly. Failures are silent on purpose: CI and a downloaded tarball are
# both legitimate places to build from, and neither has to be a git repository.
COMMIT="$(git rev-parse --short HEAD 2>/dev/null || true)"
if [[ -n "$COMMIT" ]] && ! git diff --quiet 2>/dev/null; then
    # Uncommitted changes: the commit alone would name a build that never
    # existed.
    COMMIT="$COMMIT+"
fi
BUILT="$(date -u +%Y-%m-%d)"

# Write the proxy defaults into a generated source file.
#
# Connect IQ has no compiler defines and the values from .env do not reach the
# compiler on their own — without this step the app starts with empty settings.
# The app reads them as defaults as long as nothing else is set in the phone
# settings. The file is regenerated on every build and not checked in, because
# it contains the token.
GENERATED="source/BuildDefaults.mc"

# In Monkey C string literals, backslash and quotes may only appear escaped;
# line breaks not at all.
escape_literal() {
    printf '%s' "${1//$'\n'/}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

cat > "$GENERATED" <<EOF
// Generated by build.sh — do not edit, do not check in.
import Toybox.Lang;

//! What the build knows and the source cannot: the proxy settings, where this
//! build came from, and how much it is allowed to say.
//!
//! The proxy values are empty when no .env was present at build time; then the
//! settings from the phone app apply.
module BuildDefaults {
    const PROXY_URL = "$(escape_literal "${PROXY_URL:-}")";
    const PROXY_TOKEN = "$(escape_literal "${PROXY_TOKEN:-}")";
    //! Short commit hash, "+" appended when the tree was dirty. Empty outside a
    //! git checkout.
    const COMMIT = "$(escape_literal "$COMMIT")";
    const BUILT = "$(escape_literal "$BUILT")";
    //! Log.ERROR .. Log.DEBUG. Read as a constant so the compiler can fold the
    //! comparisons away entirely.
    const LOG_LEVEL = $LOG_LEVEL;
}
EOF

if [[ -z "${PROXY_URL:-}" || -z "${PROXY_TOKEN:-}" ]]; then
    echo "Warning: PROXY_URL/PROXY_TOKEN not set — building without defaults." >&2
fi

"$CIQ_HOME/bin/monkeyc" \
    -f monkey.jungle \
    -d "$DEVICE" \
    -o "$OUTPUT" \
    -y "$CIQ_KEY" \
    -l "$TYPECHECK" \
    "$@"
echo "Built: $OUTPUT"
